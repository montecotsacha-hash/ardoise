/**
 * Expressive shape scale.
 *
 * Chrome and buttons are pills (fully rounded), cards sit on `large`/`extraLarge`,
 * and the hero surfaces use the 32 dp step, per the material-3-frosted guidance
 * to keep a single, clearly stepped radius family.
 */
